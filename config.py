def _load_env():
    """อ่าน .env (หรือไฟล์ที่ ENV_FILE ชี้ เช่น ENV_FILE=.env-practice) · ค่าที่ตั้งใน environment อยู่แล้วชนะเสมอ
    รัน 2 ตลาดพร้อมกัน = 2 process คนละ ENV_FILE และคนละ LOG_DIR"""
    env = Path(os.getenv("ENV_FILE") or HERE / ".env")
    if not env.is_absolute():
        env = HERE / env
    if env.exists():
        for line in env.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                v = v.split(" #")[0]                  # คอมเมนต์ท้ายบรรทัด
                os.environ.setdefault(k.strip(), v.strip().strip('"').strip("'"))


