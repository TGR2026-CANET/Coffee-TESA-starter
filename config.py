def _llm_url(url):
    """openai ต่อ /chat/completions ให้เอง ถ้าใส่มาด้วยจะได้ 404"""
    url = (url or "").strip().rstrip("/")
    for tail in ("/chat/completions", "/completions"):
        if url.endswith(tail):
            url = url[: -len(tail)]
    return url


